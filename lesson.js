/* 펼쳐보기의 종이색 — index.html 의 TONES 와 같은 값 */
var TONES = ['#e7dec6', '#d9cca9', '#c9b98f'];

/* net() 이 준 면 목록을 그대로 SVG 로 옮긴다 (펼친 상태 = 접기 0) */
function netSvg(key) {
  var S = (window.SOLIDS || {})[key];
  if (!S || typeof S.net !== 'function') return '';
  var F = S.net();
  var minx = 1e9, maxx = -1e9, miny = 1e9, maxy = -1e9;
  F.forEach(function (f) {
    f.pts.forEach(function (p) {
      if (p[0] < minx) minx = p[0]; if (p[0] > maxx) maxx = p[0];
      if (p[1] < miny) miny = p[1]; if (p[1] > maxy) maxy = p[1];
    });
  });
  var pad = 0.25;
  var body = F.map(function (f) {
    return '<polygon points="' +
      f.pts.map(function (p) { return p[0].toFixed(3) + ',' + p[1].toFixed(3); }).join(' ') +
      '" fill="' + (TONES[f.tone] || TONES[0]) + '" fill-opacity=".92" ' +
      'stroke="#6b5a3c" stroke-width="0.035" stroke-linejoin="round"/>';
  }).join('');
  return '<svg viewBox="' + (minx - pad).toFixed(3) + ' ' + (miny - pad).toFixed(3) + ' ' +
         (maxx - minx + pad * 2).toFixed(3) + ' ' + (maxy - miny + pad * 2).toFixed(3) +
         '" style="width:100%;max-height:32vh;height:auto">' + body + '</svg>';
}

